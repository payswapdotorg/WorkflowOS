/**
 * WORK-027: ExternalExecutionProvider.
 *
 * Generates a deterministic ExternalExecutionPackage for execution in an
 * external AI platform (ChatGPT / Claude / Z.ai native UI) via the future
 * WorkflowOS Companion browser extension.
 *
 * IMPORTANT SCOPE RULES (WORK-027):
 *   - This provider does NOT execute anything. It produces a handoff-ready
 *     package and returns status 'handoff_ready'.
 *   - It contains NO provider-specific adapters, DOM selectors, or URLs for
 *     Z.ai / ChatGPT / Claude — those belong to WORK-028/029. Provider names
 *     arrive as opaque strings validated against the catalog in the agent
 *     provider registry service.
 *   - The package contains NO secrets (no GitHub/LLM/Vercel tokens, no
 *     webhook secrets). Retrieval is gated by the one-time, short-lived
 *     handoff token mechanism (DefaultExecutionHandoffService).
 *
 * Determinism: the package content (excluding executionId + expiration, which
 * are inherently per-execution) is a pure function of the ExecutionTask. The
 * prompt itself is generated by the ExecutionPromptBuilder from the persisted
 * ImplementationContext (see /work-items — the context authority).
 *
 * PR #46 round 9 (the GENERATION-FENCED, IDENTITY-RECOVERABLE operation
 * boundary): the durable provider-operation ledger (round 8) is real, but its
 * round-8 takeover protocol did not satisfy the stronger exactly-once
 * contract — the review's three blocking findings, all corrected here:
 *
 *   1. TAKEOVER RE-RAN THE OPERATION BODY. The round-8 take-over bumped the
 *      generation and then simply called generate() again — durable
 *      single-ROW arbitration, but a singular OPERATION BODY only by
 *      determinism accident. The round-9 protocol:
 *
 *        attachOperation(identity)  ← the operation identity is durably
 *        ↓                            recorded BEFORE the body runs
 *        generate() (the body)      ← ONLY reachable when NO identity was
 *        ↓                            recorded ⇒ the body NEVER started ⇒
 *        complete(gen, result)        this is the FIRST execution
 *
 *      A recovery driver that finds a RECORDED identity RESOLVES THE
 *      OPERATION BY ITS IDENTITY ({@link resolveOperation}) — it NEVER
 *      re-runs the operation body. Take-over can therefore no longer mean
 *      "execute the operation again": either the identity is absent (the
 *      body never started — driving it is the first execution) or the
 *      identity is recorded (the operation exists — resolve it by identity).
 *      For the current PURE provider, resolution is re-derivation of the
 *      same value from the same task (valid precisely BECAUSE the operation
 *      has no side effects — this justification is the provider's own
 *      declaration, not an architecture-wide assumption). A future
 *      side-effecting provider (WORK-028/029) resolves by a platform status
 *      fetch on the identity; the round-7 keyed-convergence contract (same
 *      key → same provider operation) remains the provider-boundary
 *      guarantee for the unknowable in-flight window.
 *
 *   2. RESOLUTION WAS NOT FENCED BY GENERATION. The round-8 complete()/fail()
 *      only checked state='pending', so a STALE generation could resolve the
 *      row after a take-over — a stale FAILURE could defeat the recovery
 *      generation, and a stale SUCCESS could win merely by racing. Round 9
 *      makes takeOver() RETURN the new generation token, and
 *      complete(key, generation, result) / fail(key, generation, error) are
 *      CAS-fenced against it: a stale generation is STRUCTURALLY INCAPABLE
 *      of resolving the operation — exactly one generation (the ACTIVE
 *      driver) resolves authoritatively, for a success AND for a failure.
 *
 *   3. THE KEY WAS NOT IMMUTABLE. The round-8 register() re-armed terminally
 *      FAILED rows (generation + 1, back to pending), so one key could
 *      resolve to FAILED/result-A then COMPLETED/result-B. Round 9: COMPLETED
 *      and FAILED are BOTH terminal — register NEVER re-arms; one key
 *      identifies ONE logical operation invocation with ONE terminal result.
 *      Retryability is the driver mechanics' concern (await → take-over →
 *      resolve-by-identity), never a second operation under the same key.
 *
 * The corrected ledger design (mirrors the handoff lease):
 *
 *     operation key → one durable operation row → generation/fencing token
 *     → one active driver → operation-specific durable/provider idempotency
 *     identity → one terminal result.
 *
 * UNKEYED tasks (the mainline one-shot dispatch — the
 * DefaultExecutionService path) keep the exact pre-WORK-042 behavior: a
 * direct generation with NO ledger (each mainline execution dispatches
 * exactly once through its own record lifecycle).
 *
 * This file is private to /agents (PLAT-AC-02).
 */
import type { Logger } from '@platform/logger.js';
import type {
  ExecutionProvider,
  ExecutionSubmission,
  ExecutionTask,
  ExternalExecutionPackage,
} from './execution.types.js';
import type {
  ExecutionProviderOperationStore,
  ProviderOperationRecord,
} from './pg-execution-provider-operation-repository.js';

export interface ExternalExecutionProviderOptions {
  /**
   * How long the external handoff window stays open, in milliseconds.
   * Defaults to 1 hour. Configurable so tests can exercise expiry without
   * sleeping.
   */
  readonly packageTtlMs?: number;
  /** Injectable clock for deterministic tests. Defaults to real time. */
  readonly now?: () => Date;
  /**
   * PR #46 round 8: the DURABLE PROVIDER-OPERATION LEDGER store. REQUIRED
   * for keyed dispatches (the cross-mode handoff dispatch) — a keyed submit
   * without a store is a wiring error and fails loudly. Unkeyed (mainline)
   * submissions never touch the store.
   */
  readonly operationStore?: ExecutionProviderOperationStore;
  /**
   * How long a same-key submit awaits a PENDING ledger row's resolution
   * before TAKING OVER the drive (the process-loss recovery window).
   * Defaults to 5s. Correctness never depends on this knob (the
   * generation-fenced resolution CAS arbitrates drivers; the loser converges
   * to the winner) — it only trades await time against duplicate recovery
   * work after a crashed driver.
   */
  readonly operationResolutionWindowMs?: number;
  /** The ledger poll interval while awaiting a pending resolution. */
  readonly operationPollIntervalMs?: number;
  /** Optional structured logger (convergence/take-over observability). */
  readonly logger?: Logger;
}

/** Sentinel: the ledger row is PENDING — the operation is in flight. */
const IN_FLIGHT = Symbol('in-flight');
/**
 * Sentinel: the drive must YIELD to another driver (this driver's generation
 * is stale, or a concurrent driver recorded the identity / is resolving the
 * row) — the caller re-enters the converge/await/take-over loop.
 */
const RECOVERY_CONTINUE = Symbol('recovery-continue');
/** Type alias for the two drive outcomes that are not a submission. */
type DriveOutcome = ExecutionSubmission | typeof RECOVERY_CONTINUE;

/**
 * The maximum converge → await → take-over → drive cycles one keyed submit
 * will run before failing loudly (a pathological-contention guard — every
 * cycle costs a full resolution window, so this bound never fires in
 * practice; it exists so a permanently contended row surfaces as an error
 * instead of looping forever).
 */
const MAX_RECOVERY_CYCLES = 8;

export class ExternalExecutionProvider implements ExecutionProvider {
  readonly name = 'external';
  readonly mode = 'external' as const;

  private readonly packageTtlMs: number;
  private readonly now: () => Date;
  private readonly operationStore?: ExecutionProviderOperationStore;
  private readonly resolutionWindowMs: number;
  private readonly pollIntervalMs: number;
  private readonly logger?: Logger;

  constructor(options: ExternalExecutionProviderOptions = {}) {
    this.packageTtlMs = options.packageTtlMs ?? 60 * 60 * 1000;
    this.now = options.now ?? (() => new Date());
    this.operationStore = options.operationStore;
    this.resolutionWindowMs = options.operationResolutionWindowMs ?? 5_000;
    this.pollIntervalMs = options.operationPollIntervalMs ?? 25;
    this.logger = options.logger;
  }

  async submit(task: ExecutionTask): Promise<ExecutionSubmission> {
    const key = task.dispatchIdempotencyKey;
    if (!key) {
      // UNKEYED (the mainline one-shot dispatch): the pre-WORK-042 behavior
      // — a direct generation, no registry, no ledger row.
      return this.generate(task);
    }
    // KEYED (the cross-mode handoff dispatch): resolve through the DURABLE
    // provider-operation ledger — the row for this key IS the operation.
    const store = this.operationStore;
    if (!store) {
      throw new Error(
        `external-execution-operation-store-required: execution ${task.executionId} was submitted with dispatch idempotency key ${key}, but no durable provider-operation ledger store is wired (PR #46 round 8 — the keyed registry MUST be durable)`,
      );
    }
    const { opened } = await store.register({
      idempotencyKey: key,
      provider: task.provider,
      executionId: task.executionId,
      mode: 'external',
    });
    // The recovery loop: the original drive (generation 1) and every later
    // converged submit share ONE protocol — converge (terminal → replay /
    // stored failure), await the active driver's durable resolution, and
    // after the resolution window (process loss) TAKE OVER the drive of the
    // SAME row with a NEW GENERATION TOKEN.
    let drive: DriveOutcome | undefined = opened
      ? await this.attemptDrive(store, key, task, 1)
      : undefined;
    for (let cycle = 0; ; cycle++) {
      if (drive !== undefined && drive !== RECOVERY_CONTINUE) {
        return drive;
      }
      if (cycle >= MAX_RECOVERY_CYCLES) {
        throw new Error(
          `external-execution-recovery-exhausted: the provider operation ${key} for execution ${task.executionId} did not converge within ${MAX_RECOVERY_CYCLES} recovery cycles (pathological contention — the row remains the single durable operation; retry the dispatch)`,
        );
      }
      // Converge through the row: COMPLETED → replay; FAILED → the stored
      // terminal failure; PENDING → await the active driver.
      const row = await store.get(key);
      const converged = this.convergeFrom(row, key);
      if (converged !== IN_FLIGHT) {
        return converged;
      }
      const resolved = await this.awaitResolution(store, key);
      if (resolved) {
        return this.convergeFrom(resolved, key) as ExecutionSubmission;
      }
      // The window elapsed — the presumed-dead driver. The take-over CAS
      // records the recovery drive on the SAME row (generation + 1) and
      // RETURNS THE NEW GENERATION TOKEN (the fencing token this driver must
      // present to complete/fail — every previous generation becomes
      // structurally incapable of resolving the operation).
      const takeover = await store.takeOver(key);
      if (!takeover.tookOver) {
        continue; // the row resolved in the interim — converge next cycle
      }
      this.logger?.info('execution.external.provider-operation-takeover', {
        idempotencyKey: key,
        executionId: task.executionId,
        generation: takeover.generation,
        resolutionWindowMs: this.resolutionWindowMs,
      });
      drive = await this.attemptDrive(store, key, task, takeover.generation!);
    }
  }

  /**
   * DRIVE the ONE ledger operation for the key as the ACTIVE driver of
   * `generation`. The protocol (round 9 — the attach-before-body ordering):
   *
   *   - The row resolved → converge (replay / the stored failure).
   *   - The row's generation moved on → this driver is STALE: yield (the
   *     caller converges onto the active driver's outcome; a stale driver
   *     never resolves the row).
   *   - The operation IDENTITY is RECORDED → the operation was STARTED
   *     (possibly by a driver that died mid-flight): RESOLVE BY IDENTITY —
   *     {@link resolveOperation} — NEVER a body re-run.
   *   - The identity is ABSENT → the body NEVER started: derive the identity
   *     ({@link openOperation}), durably ATTACH it (the CAS), and run the
   *     operation body — the FIRST execution under this identity.
   */
  private async attemptDrive(
    store: ExecutionProviderOperationStore,
    key: string,
    task: ExecutionTask,
    generation: number,
  ): Promise<DriveOutcome> {
    const row = await store.get(key);
    if (!row) {
      // Unreachable in practice (register/takeOver created the row); yield
      // defensively so the caller re-resolves.
      return RECOVERY_CONTINUE;
    }
    if (row.state !== 'pending') {
      // A terminal row always converges (replay or the stored failure) — it
      // can never yield the in-flight marker.
      return this.convergeFrom(row, key) as ExecutionSubmission;
    }
    if (row.generation !== generation) {
      // A newer generation owns the drive — this driver is stale. It must
      // NOT resolve the row (the generation-fenced CAS would reject it
      // anyway); it converges onto the active driver's outcome instead.
      return RECOVERY_CONTINUE;
    }
    if (row.providerOperationHandle != null) {
      // The operation identity is RECORDED — the operation was STARTED (the
      // attach precedes the body): resolve the STARTED operation by its
      // identity. NEVER the operation body.
      return this.resolveByIdentity(
        store,
        key,
        task,
        generation,
        row.providerOperationHandle,
      );
    }
    // The identity is NOT recorded — the operation body NEVER started (the
    // attach precedes the body): this drive is the FIRST execution.
    const handle = await this.openOperation(key);
    const attached = await store.attachOperation(key, generation, handle);
    if (!attached) {
      // The CAS lost: a concurrent driver attached the identity first, the
      // generation moved on, or the row resolved. Re-read: if the identity
      // is now recorded at OUR generation, resolve by it; otherwise yield.
      const fresh = await store.get(key);
      if (
        fresh &&
        fresh.state === 'pending' &&
        fresh.generation === generation &&
        fresh.providerOperationHandle != null
      ) {
        return this.resolveByIdentity(
          store,
          key,
          task,
          generation,
          fresh.providerOperationHandle,
        );
      }
      return RECOVERY_CONTINUE;
    }
    try {
      const submission = await this.generate(task);
      return await this.settle(store, key, task, generation, submission);
    } catch (err) {
      return this.failDrive(store, key, task, generation, err);
    }
  }

  /**
   * RESOLVE the STARTED operation by its durable identity (the recovery path
   * for a row that already records its provider operation handle): the
   * provider returns the ONE operation's outcome through the
   * contract-bound {@link resolveOperation} seam — the operation body is
   * NEVER re-run here. The resolution commits through the same
   * generation-fenced CAS as a body drive.
   */
  private async resolveByIdentity(
    store: ExecutionProviderOperationStore,
    key: string,
    task: ExecutionTask,
    generation: number,
    handle: string,
  ): Promise<DriveOutcome> {
    this.logger?.info(
      'execution.external.provider-operation-resolve-by-identity',
      { idempotencyKey: key, executionId: task.executionId, generation, handle },
    );
    try {
      const submission = await this.resolveOperation(handle, task);
      return await this.settle(store, key, task, generation, submission);
    } catch (err) {
      return this.failDrive(store, key, task, generation, err);
    }
  }

  /**
   * SETTLE a resolved submission through the GENERATION-FENCED resolution
   * CAS: the ACTIVE driver's generation stores the ONE terminal result; a
   * CAS loss means the driver is stale or lost the race — it converges to
   * the winner's recorded outcome (a still-pending row at a NEWER generation
   * means the active recovery driver owns the resolution — this driver
   * yields and awaits it; it NEVER returns its own lookalike result).
   */
  private async settle(
    store: ExecutionProviderOperationStore,
    key: string,
    task: ExecutionTask,
    generation: number,
    submission: ExecutionSubmission,
  ): Promise<DriveOutcome> {
    const { completed, current } = await store.complete(
      key,
      generation,
      submission,
    );
    if (completed) {
      return submission;
    }
    if (current && current.state === 'completed' && current.submission) {
      this.logger?.info(
        'execution.external.provider-operation-converged-late-driver',
        { idempotencyKey: key, executionId: task.executionId },
      );
      return current.submission;
    }
    if (current && current.state === 'failed') {
      throw new Error(
        current.errorMessage ??
          `external-execution-operation-failed: the provider operation ${key} already resolved as failed`,
      );
    }
    // Still pending at a NEWER generation: the active recovery driver owns
    // the resolution — yield and converge onto its outcome.
    return RECOVERY_CONTINUE;
  }

  /**
   * Record a failed drive through the GENERATION-FENCED failure CAS. If the
   * CAS wins, the failure is the operation's terminal outcome. If it loses,
   * this driver's generation is STALE (superseded by a take-over): its
   * failure is structurally DISCARDED — it can never defeat the active
   * recovery generation — and the driver converges to the row's recorded or
   * eventual outcome instead (a COMPLETED row still resolves the same key;
   * a still-pending row is the active driver's to resolve).
   */
  private async failDrive(
    store: ExecutionProviderOperationStore,
    key: string,
    task: ExecutionTask,
    generation: number,
    err: unknown,
  ): Promise<DriveOutcome> {
    await store.fail(key, generation, (err as Error).message);
    const row = await store.get(key);
    if (row && row.state === 'completed' && row.submission) {
      this.logger?.info(
        'execution.external.provider-operation-converged-after-failure',
        { idempotencyKey: key, executionId: task.executionId },
      );
      return row.submission;
    }
    if (row && row.state === 'failed') {
      throw new Error(
        row.errorMessage ??
          `external-execution-operation-failed: the provider operation ${key} resolved as failed`,
      );
    }
    // Still pending at a NEWER generation: this stale driver's failure was
    // DISCARDED (0 rows — the generation fence); the active recovery driver
    // owns the resolution. Yield and converge onto its outcome.
    return RECOVERY_CONTINUE;
  }

  /**
   * Map a ledger row to the converged submit outcome: COMPLETED → REPLAY the
   * stored submission; FAILED → surface the stored terminal failure (round 9:
   * the key is immutable — a terminally failed operation is a KNOWN outcome,
   * never re-armed by a later same-key submit); PENDING → the in-flight
   * marker (await/take over).
   */
  private convergeFrom(
    record: ProviderOperationRecord | null,
    key: string,
  ): ExecutionSubmission | typeof IN_FLIGHT {
    if (!record) {
      // Unreachable in practice (register returned opened:false → the row
      // exists); treat defensively as in-flight so the caller re-resolves.
      return IN_FLIGHT;
    }
    if (record.state === 'completed') {
      if (!record.submission) {
        throw new Error(
          `external-execution-operation-result-missing: the completed provider operation ${key} has no stored submission (ledger corruption)`,
        );
      }
      this.logger?.info(
        'execution.external.provider-operation-replayed',
        { idempotencyKey: key, executionId: record.executionId },
      );
      return record.submission;
    }
    if (record.state === 'failed') {
      throw new Error(
        record.errorMessage ??
          `external-execution-operation-failed: the provider operation ${key} resolved as failed`,
      );
    }
    return IN_FLIGHT;
  }

  /**
   * Await a PENDING ledger row's durable resolution, polling the ledger
   * until the row reaches a terminal state (COMPLETED/FAILED — returns the
   * row) or the resolution window elapses (returns null — the presumed-dead
   * driver; the caller takes over the drive of the SAME row).
   */
  private async awaitResolution(
    store: ExecutionProviderOperationStore,
    key: string,
  ): Promise<ProviderOperationRecord | null> {
    const deadline = Date.now() + this.resolutionWindowMs;
    for (;;) {
      await new Promise((resolve) => setTimeout(resolve, this.pollIntervalMs));
      const row = await store.get(key);
      if (row && row.state !== 'pending') {
        return row;
      }
      if (Date.now() >= deadline) {
        return null;
      }
    }
  }

  /**
   * PR #46 round 9 (the operation-identity seam): derive the DURABLE
   * PROVIDER-SIDE IDENTITY of the ONE operation for the key — WITHOUT side
   * effects. The identity is recorded in the ledger (attachOperation) BEFORE
   * the operation body runs, so a recorded identity PROVES the operation was
   * started (a recovery driver resolves it by identity — never a body
   * re-run), and an absent identity PROVES the body never started. The
   * default derivation is deterministic from the key; a platform-backed
   * provider (WORK-028/029) derives its own locally-derivable operation
   * identity (e.g. the idempotency key it forwards to the platform).
   * Protected so tests can instrument/park the pre-identity crash point.
   */
  protected async openOperation(idempotencyKey: string): Promise<string> {
    return `external-package:${idempotencyKey}`;
  }

  /**
   * PR #46 round 9 (the resolve-by-identity seam): resolve the STARTED
   * operation by its durable identity and return the ONE operation's
   * outcome. MUST NEVER start a SECOND provider operation: a platform-backed
   * provider (WORK-028/029) performs a status fetch on the identity,
   * starting the operation ONLY if it never started under this identity
   * (the FIRST execution — never a duplicate; the round-7 keyed-convergence
   * contract covers the unknowable in-flight window). The DEFAULT provider's
   * operations are PURE (deterministic package construction): resolution is
   * RE-DERIVATION of the same value from the same task — valid precisely
   * because the operation has no side effects. This is the provider-side
   * same-key convergence guarantee that makes the take-over recovery sound
   * WITHOUT assuming provider determinism architecture-wide. Protected so
   * tests can instrument/park the recovery-resolution point.
   */
  protected async resolveOperation(
    providerOperationHandle: string,
    task: ExecutionTask,
  ): Promise<ExecutionSubmission> {
    void providerOperationHandle; // the default identity is the key itself —
    // pure re-derivation does not need the handle (platform providers do).
    return this.derive(task);
  }

  /**
   * Generate the package submission (the provider operation body — the FIRST
   * execution path; reachable ONLY after the operation identity was durably
   * attached to the ledger row). Protected so tests can instrument/park the
   * operation body itself (the crash-point simulations — the deepest
   * provider-operation point, mirroring the native suite's
   * ParkableAgentAdapter).
   */
  protected async generate(task: ExecutionTask): Promise<ExecutionSubmission> {
    return this.derive(task);
  }

  /** The pure package derivation shared by the drive + the resolution seams. */
  private async derive(task: ExecutionTask): Promise<ExecutionSubmission> {
    const expiresAt = new Date(this.now().getTime() + this.packageTtlMs);

    // Deterministic branch suggestion: when the authoritative implementation
    // branch is unknown, suggest the conventional feature branch for the
    // work item label (e.g. WORK-001 → feat/work-001). The external agent
    // MAY use it; WorkflowOS never treats this as authoritative — the branch
    // becomes real only through observed GitHub state.
    const branch =
      task.implementationBranch ?? `feat/${task.workItemLabel.toLowerCase()}`;

    const repositoryOwner = task.repositoryOwner;
    const repositoryName = task.repositoryName;

    const pkg: ExternalExecutionPackage = {
      executionId: task.executionId,
      mode: 'external',
      projectId: task.projectId,
      workItemId: task.workItemId,
      workItemLabel: task.workItemLabel,
      workOrderId: task.workOrderId,
      implementationContextId: task.implementationContextId,
      provider: task.provider,
      model: task.model,
      repository: {
        owner: repositoryOwner,
        name: repositoryName,
        url:
          repositoryOwner && repositoryName
            ? `https://github.com/${repositoryOwner}/${repositoryName}`
            : null,
        defaultBranch: task.repositoryDefaultBranch,
      },
      branch,
      prompt: task.prompt,
      structuredInstructions: [...task.instructions],
      verificationRequirements: [...task.verificationRequirements],
      expectedOutputs: [...task.expectedOutputs],
      browserTestRequirements: [],
      returnCallback: {
        eventsPath: `/execution/${task.executionId}/events`,
        eventTypes: ['started', 'progress', 'completed', 'failed'],
        auth: 'x-callback-token',
        note:
          'POST JSON events to this path with the scoped x-callback-token ' +
          'header issued when the session was prepared (NOT a WorkflowOS API ' +
          'key). The callback token is scoped to THIS execution and to event ' +
          'ingestion only. Events update ONLY the execution record — ' +
          'WorkflowOS observes authoritative GitHub/CI/verification/review ' +
          'state through its own boundaries. External execution can never ' +
          'declare MERGED/VERIFIED/PASS/APPROVED.',
      },
      expiration: expiresAt.toISOString(),
    };

    return {
      executionId: task.executionId,
      provider: task.provider,
      mode: 'external',
      status: 'handoff_ready',
      externalSessionRef: null,
      package: pkg,
      expiresAt,
    };
  }
}
